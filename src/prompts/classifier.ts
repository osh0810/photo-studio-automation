export function buildUserPrompt(input: ClassificationInput): string {
	const { customer, message } = input;

	const customerBlock = customer
		? [
				"[고객 정보]",
				`이름: ${customer.고객명}`,
				`ID: ${customer.고객ID}`,
				`현재 단계: ${customer.현재단계}`,
				`원본발송: ${customer.원본발송일 || "-"}`,
				`셀렉수신: ${customer.셀렉수신일 || "-"}`,
				`보정본발송: ${customer.보정본발송일 || "-"}`,
				`추가보정요청: ${customer.추가보정요청일 || "-"}`,
				`비고: ${customer.비고 || "-"}`,
			].join("\n")
		: "[고객 정보]\n신규 고객 (DB 미등록)";

	const messageBlock = [
		"[수신 메시지]",
		`"${message.원문}"`,
		"",
		`수신 시각: ${message.수신시각}`,
		`메시지 타입: ${message.타입}`,
	].join("\n");

	return `${customerBlock}\n\n${messageBlock}`;
}
